package com.example.workspace.service;

import org.flywaydb.core.Flyway;
import org.flywaydb.core.api.FlywayException;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.testcontainers.containers.PostgreSQLContainer;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;

import java.sql.*;
import java.util.*;

import static org.junit.jupiter.api.Assertions.*;

@Testcontainers(disabledWithoutDocker = true)
class PostgresMigrationTest {
    @Container static final PostgreSQLContainer<?> database = new PostgreSQLContainer<>("postgres:16-alpine");
    private String schema;

    @BeforeEach void isolatedSchema() throws Exception {
        schema = "qa_" + UUID.randomUUID().toString().replace("-", "");
        try (Connection connection = database.createConnection("")) {
            connection.createStatement().execute("CREATE SCHEMA " + schema);
        }
    }

    private Flyway flyway(String target) {
        return Flyway.configure().dataSource(database.getJdbcUrl(), database.getUsername(), database.getPassword())
                .schemas(schema).defaultSchema(schema).locations("classpath:db/migration")
                .baselineOnMigrate(true).baselineVersion("1").target(target).load();
    }

    private Connection connection() throws Exception {
        Connection connection = database.createConnection("");
        connection.setSchema(schema);
        return connection;
    }

    @Test void freshDatabaseRepairsV1AndHasFullNullableSeriesSchema() throws Exception {
        assertEquals(2, flyway("latest").migrate().migrationsExecuted);
        verifySchema();
    }

    @Test void previouslyAppliedV1IsRepairedWithoutChecksumChanges() throws Exception {
        assertEquals(1, flyway("1").migrate().migrationsExecuted);
        try (Connection connection = connection(); ResultSet columns = connection.getMetaData().getColumns(null, schema, "reservations", null)) {
            assertTrue(columns.next());
            assertEquals("series_id", columns.getString("COLUMN_NAME"));
            assertFalse(columns.next());
        }
        assertEquals(1, flyway("latest").migrate().migrationsExecuted);
        flyway("latest").validate();
        verifySchema();
    }

    @Test void legacySchemaWithoutHistoryPreservesExistingBookingAndConstraints() throws Exception {
        try (Connection connection = connection(); Statement statement = connection.createStatement()) {
            statement.execute("""
                    CREATE TABLE bookable_resources (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      code VARCHAR(32) NOT NULL UNIQUE, name VARCHAR(255) NOT NULL,
                      type VARCHAR(255) NOT NULL, building VARCHAR(255) NOT NULL, floor_number INTEGER,
                      capacity INTEGER NOT NULL, active BOOLEAN NOT NULL, approval_required BOOLEAN NOT NULL)
                    """);
            statement.execute("""
                    CREATE TABLE reservations (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      resource_id BIGINT NOT NULL REFERENCES bookable_resources(id),
                      booked_by VARCHAR(255) NOT NULL, title VARCHAR(255) NOT NULL,
                      starts_at TIMESTAMP WITH TIME ZONE NOT NULL, ends_at TIMESTAMP WITH TIME ZONE NOT NULL,
                      status VARCHAR(255) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL)
                    """);
            statement.execute("CREATE INDEX idx_reservation_resource_time ON reservations(resource_id,starts_at,ends_at)");
            statement.execute("INSERT INTO bookable_resources VALUES (41,'LEGACY','Legacy room','ROOM','HQ',1,5,true,false)");
            statement.execute("""
                    INSERT INTO reservations VALUES (71,41,'alice','Preserve me',
                    '2030-01-06T10:00:00Z','2030-01-06T11:00:00Z','CONFIRMED','2026-01-01T00:00:00Z')
                    """);
        }
        assertEquals(1, flyway("latest").migrate().migrationsExecuted);
        try (Connection connection = connection(); ResultSet row = connection.createStatement().executeQuery("SELECT * FROM reservations WHERE id=71")) {
            assertTrue(row.next());
            assertEquals(41, row.getLong("resource_id"));
            assertEquals("alice", row.getString("booked_by"));
            assertEquals("Preserve me", row.getString("title"));
            assertEquals("CONFIRMED", row.getString("status"));
            assertEquals(java.time.Instant.parse("2030-01-06T10:00:00Z"), row.getObject("starts_at", java.time.OffsetDateTime.class).toInstant());
            assertEquals(java.time.Instant.parse("2030-01-06T11:00:00Z"), row.getObject("ends_at", java.time.OffsetDateTime.class).toInstant());
            assertEquals(java.time.Instant.parse("2026-01-01T00:00:00Z"), row.getObject("created_at", java.time.OffsetDateTime.class).toInstant());
            assertNull(row.getObject("series_id"));
            assertFalse(row.next());
        }
        verifySchema();
    }

    @Test void incompleteV1WithRowsFailsSafelyInsteadOfDiscardingData() throws Exception {
        flyway("1").migrate();
        try (Connection connection = connection()) {
            connection.createStatement().execute("INSERT INTO reservations(series_id) VALUES ('00000000-0000-0000-0000-000000000001')");
        }
        assertThrows(FlywayException.class, () -> flyway("latest").migrate());
        try (Connection connection = connection(); ResultSet rows = connection.createStatement().executeQuery("SELECT count(*) FROM reservations")) {
            assertTrue(rows.next());
            assertEquals(1, rows.getLong(1));
        }
    }

    private void verifySchema() throws Exception {
        try (Connection connection = connection()) {
            DatabaseMetaData metadata = connection.getMetaData();
            Set<String> required = new HashSet<>(List.of("id", "resource_id", "booked_by", "title", "starts_at", "ends_at", "status", "created_at"));
            try (ResultSet columns = metadata.getColumns(null, schema, "reservations", null)) {
                boolean seriesFound = false;
                while (columns.next()) {
                    String column = columns.getString("COLUMN_NAME");
                    if (column.equals("series_id")) {
                        seriesFound = true;
                        assertEquals(DatabaseMetaData.columnNullable, columns.getInt("NULLABLE"));
                        assertEquals("uuid", columns.getString("TYPE_NAME"));
                    } else if (required.remove(column)) {
                        assertEquals(DatabaseMetaData.columnNoNulls, columns.getInt("NULLABLE"), column);
                    }
                }
                assertTrue(seriesFound);
                assertTrue(required.isEmpty(), required.toString());
            }
            try (ResultSet keys = metadata.getPrimaryKeys(null, schema, "reservations")) {
                assertTrue(keys.next());
                assertEquals("id", keys.getString("COLUMN_NAME"));
            }
            try (ResultSet keys = metadata.getImportedKeys(null, schema, "reservations")) {
                assertTrue(keys.next());
                assertEquals("resource_id", keys.getString("FKCOLUMN_NAME"));
                assertEquals("bookable_resources", keys.getString("PKTABLE_NAME"));
            }
            Map<String, List<String>> indexes = new HashMap<>();
            try (ResultSet index = metadata.getIndexInfo(null, schema, "reservations", false, false)) {
                while (index.next()) indexes.computeIfAbsent(index.getString("INDEX_NAME"), ignored -> new ArrayList<>()).add(index.getString("COLUMN_NAME"));
            }
            assertEquals(List.of("resource_id", "starts_at", "ends_at"), indexes.get("idx_reservation_resource_time"));
            assertEquals(List.of("series_id"), indexes.get("idx_reservation_series_id"));
            boolean uniqueCode = false;
            try (ResultSet index = metadata.getIndexInfo(null, schema, "bookable_resources", true, false)) {
                while (index.next()) uniqueCode |= "code".equals(index.getString("COLUMN_NAME"));
            }
            assertTrue(uniqueCode);
        }
    }
}
