package db.migration;

import org.flywaydb.core.api.FlywayException;
import org.flywaydb.core.api.migration.BaseJavaMigration;
import org.flywaydb.core.api.migration.Context;

import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.Locale;
import java.util.Set;

public class V2__repair_schema_and_add_series_support extends BaseJavaMigration {
    private static final Set<String> SUPPORTED_DATABASES = Set.of("h2", "postgresql");

    @Override
    public void migrate(Context context) throws Exception {
        Connection connection = context.getConnection();
        verifyDatabase(connection);
        createCoreTables(connection);
        repairReservationsTable(connection);
    }

    private void verifyDatabase(Connection connection) throws SQLException {
        String database = connection.getMetaData().getDatabaseProductName().toLowerCase(Locale.ROOT);
        if (SUPPORTED_DATABASES.stream().noneMatch(database::contains)) {
            throw new FlywayException("Workspace Hub schema migration supports PostgreSQL and H2 only");
        }
    }

    private void createCoreTables(Connection connection) throws SQLException {
        if (!tableExists(connection, "bookable_resources")) {
            execute(connection, """
                    CREATE TABLE bookable_resources (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        code VARCHAR(32) NOT NULL UNIQUE,
                        name VARCHAR(255) NOT NULL,
                        type VARCHAR(255) NOT NULL,
                        building VARCHAR(255) NOT NULL,
                        floor_number INTEGER,
                        capacity INTEGER NOT NULL,
                        active BOOLEAN NOT NULL,
                        approval_required BOOLEAN NOT NULL
                    )
                    """);
        }
        if (!tableExists(connection, "audit_events")) {
            execute(connection, """
                    CREATE TABLE audit_events (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        actor VARCHAR(255) NOT NULL,
                        action VARCHAR(255) NOT NULL,
                        target VARCHAR(255) NOT NULL,
                        occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
                    )
                    """);
        }
    }

    private void repairReservationsTable(Connection connection) throws SQLException {
        if (!tableExists(connection, "reservations")) {
            execute(connection, """
                    CREATE TABLE reservations (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        resource_id BIGINT NOT NULL,
                        booked_by VARCHAR(255) NOT NULL,
                        title VARCHAR(255) NOT NULL,
                        starts_at TIMESTAMP WITH TIME ZONE NOT NULL,
                        ends_at TIMESTAMP WITH TIME ZONE NOT NULL,
                        status VARCHAR(255) NOT NULL,
                        created_at TIMESTAMP WITH TIME ZONE NOT NULL,
                        series_id UUID,
                        CONSTRAINT fk_reservation_resource
                            FOREIGN KEY (resource_id) REFERENCES bookable_resources(id)
                    )
                    """);
        } else {
            ensureRepairable(connection);
            addColumnIfMissing(connection, "id", "BIGINT GENERATED BY DEFAULT AS IDENTITY");
            addColumnIfMissing(connection, "resource_id", "BIGINT NOT NULL");
            addColumnIfMissing(connection, "booked_by", "VARCHAR(255) NOT NULL");
            addColumnIfMissing(connection, "title", "VARCHAR(255) NOT NULL");
            addColumnIfMissing(connection, "starts_at", "TIMESTAMP WITH TIME ZONE NOT NULL");
            addColumnIfMissing(connection, "ends_at", "TIMESTAMP WITH TIME ZONE NOT NULL");
            addColumnIfMissing(connection, "status", "VARCHAR(255) NOT NULL");
            addColumnIfMissing(connection, "created_at", "TIMESTAMP WITH TIME ZONE NOT NULL");
            addColumnIfMissing(connection, "series_id", "UUID");
            if (!hasPrimaryKey(connection, "reservations")) {
                execute(connection, "ALTER TABLE reservations ADD CONSTRAINT pk_reservations PRIMARY KEY (id)");
            }
            if (!hasForeignKey(connection, "reservations", "resource_id")) {
                execute(connection, """
                        ALTER TABLE reservations ADD CONSTRAINT fk_reservation_resource
                        FOREIGN KEY (resource_id) REFERENCES bookable_resources(id)
                        """);
            }
        }
        execute(connection, """
                CREATE INDEX IF NOT EXISTS idx_reservation_resource_time
                ON reservations(resource_id, starts_at, ends_at)
                """);
        execute(connection, """
                CREATE INDEX IF NOT EXISTS idx_reservation_series_id
                ON reservations(series_id)
                """);
    }

    private void ensureRepairable(Connection connection) throws SQLException {
        boolean missingRequiredColumn = !columnExists(connection, "reservations", "id")
                || !columnExists(connection, "reservations", "resource_id")
                || !columnExists(connection, "reservations", "booked_by")
                || !columnExists(connection, "reservations", "title")
                || !columnExists(connection, "reservations", "starts_at")
                || !columnExists(connection, "reservations", "ends_at")
                || !columnExists(connection, "reservations", "status")
                || !columnExists(connection, "reservations", "created_at");
        if (missingRequiredColumn && rowCount(connection, "reservations") > 0) {
            throw new FlywayException("Cannot repair incomplete reservations table because it contains rows");
        }
    }

    private void addColumnIfMissing(Connection connection, String column, String definition) throws SQLException {
        if (!columnExists(connection, "reservations", column)) {
            execute(connection, "ALTER TABLE reservations ADD COLUMN " + column + " " + definition);
        }
    }

    private boolean tableExists(Connection connection, String table) throws SQLException {
        DatabaseMetaData metadata = connection.getMetaData();
        try (ResultSet tables = metadata.getTables(null, connection.getSchema(), null, new String[]{"TABLE"})) {
            while (tables.next()) {
                if (table.equalsIgnoreCase(tables.getString("TABLE_NAME"))) return true;
            }
        }
        return false;
    }

    private boolean columnExists(Connection connection, String table, String column) throws SQLException {
        DatabaseMetaData metadata = connection.getMetaData();
        try (ResultSet columns = metadata.getColumns(null, connection.getSchema(), null, null)) {
            while (columns.next()) {
                if (table.equalsIgnoreCase(columns.getString("TABLE_NAME"))
                        && column.equalsIgnoreCase(columns.getString("COLUMN_NAME"))) return true;
            }
        }
        return false;
    }

    private boolean hasPrimaryKey(Connection connection, String table) throws SQLException {
        DatabaseMetaData metadata = connection.getMetaData();
        try (ResultSet keys = metadata.getPrimaryKeys(null, connection.getSchema(), table)) {
            if (keys.next()) return true;
        }
        try (ResultSet keys = metadata.getPrimaryKeys(null, connection.getSchema(), table.toUpperCase(Locale.ROOT))) {
            return keys.next();
        }
    }

    private boolean hasForeignKey(Connection connection, String table, String column) throws SQLException {
        DatabaseMetaData metadata = connection.getMetaData();
        if (hasForeignKey(metadata, connection.getSchema(), table, column)) return true;
        return hasForeignKey(metadata, connection.getSchema(), table.toUpperCase(Locale.ROOT), column);
    }

    private boolean hasForeignKey(DatabaseMetaData metadata, String schema, String table, String column)
            throws SQLException {
        try (ResultSet keys = metadata.getImportedKeys(null, schema, table)) {
            while (keys.next()) {
                if (column.equalsIgnoreCase(keys.getString("FKCOLUMN_NAME"))) return true;
            }
        }
        return false;
    }

    private long rowCount(Connection connection, String table) throws SQLException {
        try (Statement statement = connection.createStatement();
             ResultSet result = statement.executeQuery("SELECT COUNT(*) FROM " + table)) {
            result.next();
            return result.getLong(1);
        }
    }

    private void execute(Connection connection, String sql) throws SQLException {
        try (Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }
}
